y_zoom = [-0.7, 1.5];

rectangle('Position', ...
    [x_zoom(1), y_zoom(1), diff(x_zoom), diff(y_zoom)], ...
    'LineStyle','-', ...
    'LineWidth',1.2, ...
    'EdgeColor','k');

%% Inset zoom Subplot 2
axInset2 = axes('Position',[0.28 0.65 0.30 0.25]);
hold(axInset2,'on'); grid(axInset2,'on'); box(axInset2,'on');

% ===== Leader inset =====
