%% ==== Load 2 files ====
clear all;close all;clc;
data1 = load('velocities_data.mat');            % v_time, v_value, w_time, w_value
data2 = load('FollowersVelocityData.mat');      % sim_time, LinearVel, AngularVel, num_robots

v_time     = data1.v_time;
v_value    = data1.v_value;
w_time     = data1.w_time;
w_value    = data1.w_value;

sim_time   = data2.sim_time;
LinearVel  = data2.LinearVel;
AngularVel = data2.AngularVel;
num_followers = size(LinearVel,1);

colors = lines(num_followers);
%% ===== MARKER SETUP (density balanced) =====
nMarker = 12;   % số marker mong muốn trên mỗi đường

idx_mark_leader = round(linspace(1, length(v_time), nMarker));
idx_mark_follower = round(linspace(1, length(sim_time), nMarker));

markers  = {'o','s','^','d','v'};   % 5 marker
hLegend = gobjects(num_followers+1,1);
%% ===================== Subplot 1: Linear velocity =======================
figure;
hold on; grid on;

% ===== Leader =====
plot(v_time, v_value, 'k-', 'LineWidth', 1.5);
plot(v_time(idx_mark_leader), v_value(idx_mark_leader), ...
    'LineStyle','none','Marker',markers{1}, ...
    'MarkerEdgeColor','k','MarkerFaceColor','k','MarkerSize',6);

% Handle legend leader
hLegend(1) = plot(nan,nan,'k-', ...
    'LineWidth',1.5, ...
    'Marker',markers{1}, ...
    'MarkerSize',6, ...
    'MarkerFaceColor','k');

for j = 1:num_followers
    % đường liền
    plot(sim_time, LinearVel(j,:), '-', ...
        'Color', colors(j,:), 'LineWidth',1.2);

    % marker
    plot(sim_time(idx_mark_follower), ...
         LinearVel(j,idx_mark_follower), ...
         'LineStyle','none', ...
         'Marker',markers{j+1}, ...
         'MarkerEdgeColor',colors(j,:), ...
         'MarkerFaceColor',colors(j,:), ...
         'MarkerSize',5);

    % handle legend follower j
    hLegend(j+1) = plot(nan,nan,'-', ...
        'Color',colors(j,:), ...
        'LineWidth',1.2, ...
        'Marker',markers{j+1}, ...
        'MarkerSize',5, ...
        'MarkerFaceColor',colors(j,:));
end

xlabel('Time (s)', 'Interpreter','latex');
ylabel('$v$ (m/s)', 'Interpreter','latex');
title('Linear velocities (Leader vs Followers)', 'Interpreter','latex');
legend(hLegend, ...
    [{'$Reference^{[13]}$'}, ...
     arrayfun(@(j) sprintf('Follower %d',j), 1:num_followers, ...
              'UniformOutput',false)], ...
    'Interpreter','latex','Location','best');

% ===== Zoomed region rectangle (main axes) =====
x_zoom = [10 20];
y_zoom = [4, 10];

rectangle('Position', ...
    [x_zoom(1), y_zoom(1), diff(x_zoom), diff(y_zoom)], ...
    'LineStyle','-', ...
    'LineWidth',1.2, ...
    'EdgeColor','k');
%% Inset zoom Subplot 1
axInset1 = axes('Position',[0.28 0.65 0.30 0.25]);
hold(axInset1,'on'); grid(axInset1,'on'); box(axInset1,'on');

% ===== Leader inset =====
plot(axInset1, v_time, v_value, 'k-', 'LineWidth', 1.3);
plot(axInset1, v_time(idx_mark_leader), v_value(idx_mark_leader), ...
    'LineStyle','none','Marker',markers{1}, ...
    'MarkerEdgeColor','k','MarkerFaceColor','k','MarkerSize',5);

% ===== Followers inset =====
for j = 1:num_followers
    plot(axInset1, sim_time, LinearVel(j,:), '-', ...
        'Color', colors(j,:), 'LineWidth', 1.0);

    plot(axInset1, sim_time(idx_mark_follower), ...
     LinearVel(j, idx_mark_follower), ...
     'LineStyle','none','Marker',markers{j+1}, ...
     'MarkerEdgeColor',colors(j,:), ...
     'MarkerFaceColor',colors(j,:), ...
     'MarkerSize',4);
end

xlim(axInset1, [10 20]);
ylim(axInset1, [4, 10]);
title(axInset1,'');

% ===== Dashed arrow pointing to inset (figure coordinates) =====
annotation('textarrow', ...
    [0.25 0.4], ...   % x start -> x end (figure normalized)
    [0.52 0.65], ...   % y start -> y end
    'LineStyle','--', ...
    'LineWidth',1.2, ...
    'HeadLength',8, ...
    'HeadWidth',8, ...
    'Color','k', ...
    'Interpreter','latex');
