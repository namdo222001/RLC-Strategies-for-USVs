clear all;close all;clc;
load("InputConstrData.mat")
load("InputConstraints_followers.mat")
numFollowers=4;
colors = lines(numFollowers);

nMarker = 12;
idx_mark_main     = round(linspace(1, length(t), nMarker));
idx_mark_follower = round(linspace(1, length(sim_time), nMarker));

markers = {'o','s','^','d','v'};
hLegend = gobjects(numFollowers+1,1);
%% --- Plot chính ---
figure;
hold on; grid on;

% ===== Leader =====
plot(t, y, 'k-', 'LineWidth', 1.5);
plot(t(idx_mark_main), y(idx_mark_main), ...
    'LineStyle','none', ...
    'Marker',markers{1}, ...
    'MarkerEdgeColor','k', ...
    'MarkerFaceColor','k', ...
    'MarkerSize',6);

hLegend(1) = plot(nan,nan,'k-', ...
    'LineWidth',1.5, ...
    'Marker',markers{1}, ...
    'MarkerSize',6, ...
    'MarkerFaceColor','k');

% ===== Followers =====
for j = 1:numFollowers
    plot(sim_time, violations(:,j), '-', ...
        'Color', colors(j,:), ...
        'LineWidth',1.2);

    plot(sim_time(idx_mark_follower), ...
         violations(idx_mark_follower,j), ...
         'LineStyle','none', ...
         'Marker',markers{j+1}, ...
         'MarkerEdgeColor',colors(j,:), ...
         'MarkerFaceColor',colors(j,:), ...
         'MarkerSize',5);

    hLegend(j+1) = plot(nan,nan,'-', ...
        'Color',colors(j,:), ...
        'LineWidth',1.2, ...
        'Marker',markers{j+1}, ...
        'MarkerSize',5, ...
        'MarkerFaceColor',colors(j,:));
end

xlabel('Time (s)');
ylabel('||v||/a + ||\omega||/b');
title('Input Constraint');
hold off;
legend(hLegend, ...
    [{'$Reference^{[13]}$'}, ...
     arrayfun(@(j) sprintf('Follower %d',j), 1:numFollowers, ...
              'UniformOutput',false)], ...
    'Interpreter','latex','Location','best');


%% === Inset Zoom Plot ===
ax_main = gca;

ax_inset = axes('Position',[0.25 0.58 0.3 0.3]);
hold(ax_inset,'on'); grid(ax_inset,'on'); box(ax_inset,'on');

% zoom ranges
x_zoom = [0 10];
y_zoom = [0.2 0.6];

% ===== Leader inset =====
plot(ax_inset, t, y, 'k-', 'LineWidth', 1.3);
plot(ax_inset, t(idx_mark_main), y(idx_mark_main), ...
    'LineStyle','none', ...
    'Marker',markers{1}, ...
    'MarkerEdgeColor','k', ...
    'MarkerFaceColor','k', ...
    'MarkerSize',5);

% ===== Followers inset =====
for j = 1:numFollowers
    plot(ax_inset, sim_time, violations(:,j), '-', ...
        'Color', colors(j,:), 'LineWidth',1.0);

    plot(ax_inset, sim_time(idx_mark_follower), ...
         violations(idx_mark_follower,j), ...
         'LineStyle','none', ...
         'Marker',markers{j+1}, ...
         'MarkerEdgeColor',colors(j,:), ...
         'MarkerFaceColor',colors(j,:), ...
         'MarkerSize',4);
end

xlim(ax_inset, x_zoom);
ylim(ax_inset, y_zoom);
title(ax_inset, ' ');

%% Frame + Arrow
annotation('rectangle',[0.13 0.28 0.1 0.25], 'Color','k', 'LineWidth',1.0);
annotation('textarrow',[0.2 0.29], [0.53 0.58], 'LineStyle','--', ...
    'LineWidth',1.2, ...
    'HeadLength',8, ...
    'HeadWidth',8, ...
    'Color','k', ...
    'Interpreter','latex');
exportgraphics(gcf,'conpare_input_with_ejc25.pdf','ContentType','vector','BackgroundColor','none');